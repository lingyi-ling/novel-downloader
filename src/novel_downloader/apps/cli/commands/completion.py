#!/usr/bin/env python3
"""
novel_downloader.apps.cli.commands.completion
----------------------------------------------

Print a shell completion script for ``novel-cli``.

The script is generated from the argparse tree built by the registered
:class:`~novel_downloader.apps.cli.commands.base.Command` classes, so new
subcommands and options show up automatically without a second declaration.
Only a flat word list is completed (no option values), which keeps the output
portable between Bash, Zsh, Fish and PowerShell.
"""

from __future__ import annotations

import contextlib
import io
import os
import re
import sys
from argparse import ArgumentParser, Namespace, _SubParsersAction
from dataclasses import dataclass, field

from novel_downloader.apps.cli import ui
from novel_downloader.infra.i18n import t

from .base import Command, localize_help

#: Shells a completion script can be generated for.
SHELLS = ("bash", "zsh", "fish", "powershell")


@dataclass
class CompletionNode:
    """Options and nested subcommands of one argparse (sub)parser."""

    options: tuple[str, ...] = ()
    subcommands: dict[str, CompletionNode] = field(default_factory=dict)

    def words(self) -> list[str]:
        """Return the completion candidates for this node, de-duplicated."""
        return list(dict.fromkeys([*self.subcommands, *self.options]))


def _node_from_parser(parser: ArgumentParser) -> CompletionNode:
    """Recursively collect options and subcommands from an argparse parser."""
    options: list[str] = []
    subcommands: dict[str, CompletionNode] = {}

    for action in parser._actions:
        if isinstance(action, _SubParsersAction):
            for name, child in action.choices.items():
                subcommands[str(name)] = _node_from_parser(child)
        elif action.option_strings:
            options.extend(action.option_strings)

    return CompletionNode(
        options=tuple(sorted(set(options))),
        subcommands={name: subcommands[name] for name in sorted(subcommands)},
    )


def build_completion_tree(
    command_classes: list[type[Command]],
) -> CompletionNode:
    """
    Build the completion tree for ``command_classes``.

    A throw-away parser is constructed with the same registration call the CLI
    uses, then introspected. No command body is executed, so no optional
    dependency or network access is involved.
    """
    parser = ArgumentParser(prog="novel-cli", add_help=False)
    localize_help(parser)
    parser.add_argument("-v", "--version", action="version", version="novel-cli")
    parser.add_argument("--lang")

    subparsers = parser.add_subparsers(dest="command", title=t("Commands"))
    for cls in command_classes:
        cls.register(subparsers)

    return _node_from_parser(parser)


def _walk(node: CompletionNode, prefix: str = "") -> list[tuple[str, CompletionNode]]:
    """Flatten the tree into ``(space-prefixed path, node)`` pairs."""
    pairs = [(prefix, node)]
    for name, child in node.subcommands.items():
        pairs.extend(_walk(child, f"{prefix} {name}"))
    return pairs


def _case_entries(node: CompletionNode) -> list[tuple[str, list[str]]]:
    """Return ``(path, words)`` pairs, including an empty fallback case."""
    entries = [(path, child.words()) for path, child in _walk(node)]
    entries.append(("*", []))
    return entries


def _single_quote(word: str) -> str:
    """Quote ``word`` for a POSIX-shell single-quoted string (Bash/Zsh).

    A literal ``'`` is written as ``'\\''``: close the quote, emit an escaped
    quote, reopen.  Option strings come from argparse and are normally plain,
    but quoting keeps an unexpected character from breaking the script.
    """
    return "'" + word.replace("'", "'\\''") + "'"


#: Characters that cannot sit unescaped inside a double-quoted shell string.
_UNSAFE_IN_DOUBLE_QUOTES = re.compile(r"[\"'`$\\]")


def _case_pattern(pattern: str) -> str:
    """Render one ``case`` label, leaving the catch-all ``*`` as a real glob.

    Ordinary paths keep the historical ``"..."`` spelling (readable scripts);
    anything that would be expanded or would close the quote falls back to
    single quotes.
    """
    if pattern == "*":
        return "*"
    if _UNSAFE_IN_DOUBLE_QUOTES.search(pattern):
        return _single_quote(pattern)
    return f'"{pattern}"'


def _bash_script(node: CompletionNode) -> str:
    """Generate a Bash completion function."""
    lines = [
        "# bash completion for novel-cli",
        "# generated by: novel-cli completion --shell bash",
        "_novel_cli_completion() {",
        "    local cur path words i",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    path=""',
        "    for ((i = 1; i < COMP_CWORD; i++)); do",
        '        path="${path} ${COMP_WORDS[i]}"',
        "    done",
        '    case "$path" in',
    ]
    for pattern, words in _case_entries(node):
        lines.append(f"        {_case_pattern(pattern)})")
        lines.append(f"            words={_single_quote(' '.join(words))}")
        lines.append("            ;;")
    lines.extend(
        [
            "    esac",
            '    COMPREPLY=( $(compgen -W "$words" -- "$cur") )',
            "}",
            "complete -F _novel_cli_completion novel-cli",
            "",
        ]
    )
    return "\n".join(lines)


def _zsh_script(node: CompletionNode) -> str:
    """Generate a Zsh completion function."""
    lines = [
        "#compdef novel-cli",
        "# generated by: novel-cli completion --shell zsh",
        "_novel_cli_completion() {",
        "    local path i",
        "    local -a choices",
        '    path=""',
        "    for (( i = 2; i < CURRENT; i++ )); do",
        '        path="${path} ${words[i]}"',
        "    done",
        '    case "$path" in',
    ]
    for pattern, words in _case_entries(node):
        rendered = " ".join(_single_quote(word) for word in words)
        lines.append(f"        {_case_pattern(pattern)})")
        lines.append(f"            choices=({rendered})")
        lines.append("            ;;")
    lines.extend(
        [
            "    esac",
            '    compadd -- "${choices[@]}"',
            "}",
            "compdef _novel_cli_completion novel-cli",
            "",
        ]
    )
    return "\n".join(lines)


def _fish_quote(word: str) -> str:
    """Quote ``word`` for a Fish single-quoted string."""
    return "'" + word.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _fish_script(node: CompletionNode) -> str:
    """Generate a Fish completion function.

    Fish only pattern-matches in ``switch``/``case``; an ``if`` chain with
    literal ``test`` comparisons is used instead so option names containing
    glob metacharacters stay literal.  Paths without candidates are omitted,
    and an unknown path simply matches nothing (no stale candidates).

    ``commandline -pxc`` (expand + cut at cursor) yields *completed* tokens
    and, unlike plain ``-opc``, omits the token the cursor is inside -- the
    same view Bash gets from ``COMP_WORDS`` before ``COMP_CWORD``.
    """
    lines = [
        "# fish completion for novel-cli",
        "# generated by: novel-cli completion --shell fish",
        "function __novel_cli_completion",
        "    set -l tokens (commandline -pxc)",
        "    set -e tokens[1]",
        "    set -l path (string join ' ' '' $tokens)",
    ]
    branches = [(path, child.words()) for path, child in _walk(node)]
    branches = [(path, words) for path, words in branches if words]
    for index, (path, words) in enumerate(branches):
        keyword = "if" if index == 0 else "else if"
        rendered = " ".join(_fish_quote(word) for word in words)
        lines.append(f'    {keyword} test "$path" = {_fish_quote(path)}')
        lines.append(f"        printf '%s\\n' {rendered}")
    if branches:
        lines.append("    end")
    lines.extend(
        [
            "end",
            "complete -c novel-cli -f -a '(__novel_cli_completion)'",
            "",
        ]
    )
    return "\n".join(lines)


def _powershell_quote(word: str) -> str:
    """Quote a word for a PowerShell single-quoted string."""
    return "'" + word.replace("'", "''") + "'"


def _powershell_script(node: CompletionNode) -> str:
    """Generate a PowerShell ``Register-ArgumentCompleter`` script."""
    lines = [
        "# PowerShell completion for novel-cli",
        "# generated by: novel-cli completion --shell powershell",
        "Register-ArgumentCompleter -Native -CommandName 'novel-cli' -ScriptBlock {",
        "    param($wordToComplete, $commandAst, $cursorPosition)",
        "    $tokens = @($commandAst.CommandElements | ForEach-Object { $_.Value })",
        "    $path = ''",
        "    if ($tokens.Count -gt 1) {",
        "        $end = $tokens.Count - 1",
        "        # An empty word to complete means the cursor sits after a space, so",
        "        # the last token is complete; otherwise it is the partial word and",
        "        # must not take part in the path.",
        "        if ($wordToComplete) { $end-- }",
        "        if ($end -ge 1) {",
        "            $path = ' ' + (($tokens[1..$end]) -join ' ')",
        "        }",
        "    }",
        "    $choices = switch -Exact ($path) {",
    ]
    for pattern, words in _case_entries(node):
        if pattern == "*":
            lines.append("        default { @() }")
            continue
        rendered = ", ".join(_powershell_quote(word) for word in words)
        lines.append(f"        {_powershell_quote(pattern)} {{ @({rendered}) }}")
    lines.extend(
        [
            "    }",
            '    $choices | Where-Object { $_ -like "$wordToComplete*" } |',
            "        ForEach-Object {",
            "            [System.Management.Automation.CompletionResult]::new(",
            "                $_, $_, 'ParameterValue', $_",
            "            )",
            "        }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


_GENERATORS = {
    "bash": _bash_script,
    "zsh": _zsh_script,
    "fish": _fish_script,
    "powershell": _powershell_script,
}


def detect_shell(
    env: dict[str, str] | None = None, *, platform: str | None = None
) -> str:
    """
    Guess the shell to generate a script for.

    ``$SHELL`` wins when it names Bash, Zsh or Fish; otherwise Windows defaults
    to PowerShell and everything else to Bash.
    """
    values = os.environ if env is None else env
    shell = os.path.basename(str(values.get("SHELL", ""))).lower()
    if shell in {"bash", "zsh", "fish"}:
        return shell

    name = sys.platform if platform is None else platform
    return "powershell" if name.startswith("win") else "bash"


def render_completion(node: CompletionNode, shell: str) -> str:
    """Render the completion script for ``shell``."""
    return _GENERATORS[shell](node)


class CompletionCmd(Command):
    name = "completion"
    help = t("Print a shell completion script for novel-cli.")

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--shell",
            choices=SHELLS,
            help=t("Shell to generate completion for (default: auto-detect)."),
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        from . import commands

        shell = str(args.shell or detect_shell())
        node = build_completion_tree(commands)
        _emit_lf(render_completion(node, shell))


def _emit_lf(script: str) -> None:
    """Write ``script`` to stdout with LF line endings on every platform.

    Windows text-mode stdout translates ``"\\n"`` to ``"\\r\\n"``, and the
    completion script is shell *source code*: Bash and Zsh choke on CRLF
    (``$'\\r': command not found``) when a redirected script is sourced.
    Switching the stream's newline mode to ``"\\n"`` keeps the emitted bytes
    shell-clean on Windows; POSIX platforms are unaffected, and PowerShell
    accepts LF-only scripts, so all generators share this path.
    """
    # ``TextIO`` (the declared type of ``sys.stdout``) has no ``reconfigure``;
    # only the real ``TextIOWrapper`` does. Streams without it (an embedder's
    # or a test's replacement) keep the platform default. A closed or locked
    # stream raises, and is suppressed: emit un-reconfigured rather than fail
    # a command whose content is already correct.
    if isinstance(sys.stdout, io.TextIOWrapper):
        with contextlib.suppress(ValueError, OSError):
            sys.stdout.reconfigure(newline="\n")
    ui.emit(script)
