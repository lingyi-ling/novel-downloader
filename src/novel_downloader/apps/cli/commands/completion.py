#!/usr/bin/env python3
"""
novel_downloader.apps.cli.commands.completion
----------------------------------------------

Print a shell completion script for ``novel-cli``.

The script is generated from the argparse tree built by the registered
:class:`~novel_downloader.apps.cli.commands.base.Command` classes, so new
subcommands and options show up automatically without a second declaration.
Only a flat word list is completed (no option values), which keeps the output
portable between Bash, Zsh and PowerShell.
"""

from __future__ import annotations

import os
import sys
from argparse import ArgumentParser, Namespace, _SubParsersAction
from dataclasses import dataclass, field

from novel_downloader.apps.cli import ui
from novel_downloader.infra.i18n import t

from .base import Command, localize_help

#: Shells a completion script can be generated for.
SHELLS = ("bash", "zsh", "powershell")


@dataclass
class CompletionNode:
    """Options and nested subcommands of one argparse (sub)parser."""

    options: tuple[str, ...] = ()
    subcommands: dict[str, CompletionNode] = field(default_factory=dict)

    def words(self) -> list[str]:
        """Return the completion candidates for this node."""
        return [*self.subcommands, *self.options]


def _node_from_parser(parser: ArgumentParser) -> CompletionNode:
    """Recursively collect options and subcommands from an argparse parser."""
    options: list[str] = []
    subcommands: dict[str, CompletionNode] = {}

    for action in parser._actions:
        if isinstance(action, _SubParsersAction):
            for name, child in action.choices.items():
                subcommands[str(name)] = _node_from_parser(child)
        elif action.option_strings:
            options.extend(action.option_strings)

    return CompletionNode(
        options=tuple(sorted(set(options))),
        subcommands={name: subcommands[name] for name in sorted(subcommands)},
    )


def build_completion_tree(
    command_classes: list[type[Command]],
) -> CompletionNode:
    """
    Build the completion tree for ``command_classes``.

    A throw-away parser is constructed with the same registration call the CLI
    uses, then introspected. No command body is executed, so no optional
    dependency or network access is involved.
    """
    parser = ArgumentParser(prog="novel-cli", add_help=False)
    localize_help(parser)
    parser.add_argument("-v", "--version", action="version", version="novel-cli")
    parser.add_argument("--lang")

    subparsers = parser.add_subparsers(dest="command", title=t("Commands"))
    for cls in command_classes:
        cls.register(subparsers)

    return _node_from_parser(parser)


def _walk(node: CompletionNode, prefix: str = "") -> list[tuple[str, CompletionNode]]:
    """Flatten the tree into ``(space-prefixed path, node)`` pairs."""
    pairs = [(prefix, node)]
    for name, child in node.subcommands.items():
        pairs.extend(_walk(child, f"{prefix} {name}"))
    return pairs


def _case_entries(node: CompletionNode) -> list[tuple[str, list[str]]]:
    """Return ``(path, words)`` pairs, including an empty fallback case."""
    entries = [(path, child.words()) for path, child in _walk(node)]
    entries.append(("*", []))
    return entries


def _bash_script(node: CompletionNode) -> str:
    """Generate a Bash completion function."""
    lines = [
        "# bash completion for novel-cli",
        "# generated by: novel-cli completion --shell bash",
        "_novel_cli_completion() {",
        "    local cur path words i",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    path=""',
        "    for ((i = 1; i < COMP_CWORD; i++)); do",
        '        path="${path} ${COMP_WORDS[i]}"',
        "    done",
        '    case "$path" in',
    ]
    for pattern, words in _case_entries(node):
        lines.append(f'        "{pattern}")')
        lines.append(f'            words="{" ".join(words)}"')
        lines.append("            ;;")
    lines.extend(
        [
            "    esac",
            '    COMPREPLY=( $(compgen -W "$words" -- "$cur") )',
            "}",
            "complete -F _novel_cli_completion novel-cli",
            "",
        ]
    )
    return "\n".join(lines)


def _zsh_script(node: CompletionNode) -> str:
    """Generate a Zsh completion function."""
    lines = [
        "#compdef novel-cli",
        "# generated by: novel-cli completion --shell zsh",
        "_novel_cli_completion() {",
        "    local path i",
        "    local -a choices",
        '    path=""',
        "    for (( i = 2; i < CURRENT; i++ )); do",
        '        path="${path} ${words[i]}"',
        "    done",
        '    case "$path" in',
    ]
    for pattern, words in _case_entries(node):
        rendered = " ".join(f"'{word}'" for word in words)
        lines.append(f'        "{pattern}")')
        lines.append(f"            choices=({rendered})")
        lines.append("            ;;")
    lines.extend(
        [
            "    esac",
            '    compadd -- "${choices[@]}"',
            "}",
            "compdef _novel_cli_completion novel-cli",
            "",
        ]
    )
    return "\n".join(lines)


def _powershell_quote(word: str) -> str:
    """Quote a word for a PowerShell single-quoted string."""
    return "'" + word.replace("'", "''") + "'"


def _powershell_script(node: CompletionNode) -> str:
    """Generate a PowerShell ``Register-ArgumentCompleter`` script."""
    lines = [
        "# PowerShell completion for novel-cli",
        "# generated by: novel-cli completion --shell powershell",
        "Register-ArgumentCompleter -Native -CommandName 'novel-cli' -ScriptBlock {",
        "    param($wordToComplete, $commandAst, $cursorPosition)",
        "    $tokens = @($commandAst.CommandElements | ForEach-Object { $_.Value })",
        "    $path = ''",
        "    if ($tokens.Count -gt 2) {",
        "        $path = ' ' + (($tokens[1..($tokens.Count - 2)]) -join ' ')",
        "    }",
        "    $choices = switch -Exact ($path) {",
    ]
    for pattern, words in _case_entries(node):
        rendered = ", ".join(_powershell_quote(word) for word in words)
        lines.append(f"        {_powershell_quote(pattern)} {{ @({rendered}) }}")
    lines.extend(
        [
            "    }",
            '    $choices | Where-Object { $_ -like "$wordToComplete*" } |',
            "        ForEach-Object {",
            "            [System.Management.Automation.CompletionResult]::new(",
            "                $_, $_, 'ParameterValue', $_",
            "            )",
            "        }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


_GENERATORS = {
    "bash": _bash_script,
    "zsh": _zsh_script,
    "powershell": _powershell_script,
}


def detect_shell(
    env: dict[str, str] | None = None, *, platform: str | None = None
) -> str:
    """
    Guess the shell to generate a script for.

    ``$SHELL`` wins when it names Bash or Zsh; otherwise Windows defaults to
    PowerShell and everything else to Bash.
    """
    values = os.environ if env is None else env
    shell = os.path.basename(str(values.get("SHELL", ""))).lower()
    if shell in {"bash", "zsh"}:
        return shell

    name = sys.platform if platform is None else platform
    return "powershell" if name.startswith("win") else "bash"


def render_completion(node: CompletionNode, shell: str) -> str:
    """Render the completion script for ``shell``."""
    return _GENERATORS[shell](node)


class CompletionCmd(Command):
    name = "completion"
    help = t("Print a shell completion script for novel-cli.")

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--shell",
            choices=SHELLS,
            help=t("Shell to generate completion for (default: auto-detect)."),
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        from . import commands

        shell = str(args.shell or detect_shell())
        node = build_completion_tree(commands)
        ui.emit(render_completion(node, shell))
