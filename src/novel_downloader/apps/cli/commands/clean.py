def _validated_site(site: str) -> str:
    """
    Return ``site`` when it is usable as one directory name, else exit 2.

    ``--site`` is joined onto the cache/raw-data root and the result is handed
    to the safe removal helper. A value such as ``..``, ``../..`` or ``/etc``
    would therefore delete a directory *outside* the application's data -- the
    one place a cleanup command must never reach. Real site keys are plain
    identifiers (``b520``, ``fanqienovel``), so an escaping value is a bad
    argument (usage error), not a runtime failure.

    :param site: Raw ``--site`` value (or an interactively entered key).
    :return: The unchanged key when it is safe to join onto a base directory.
    """
    return require_safe_site(str(site))


class CleanCmd(Command):
    name = "clean"
    help = t("Clear application logs, caches, and book data")

    @classmethod
    def register(cls, subparsers: "_SubParsersAction[ArgumentParser]") -> None:
        parser = subparsers.add_parser(
            cls.name, help=cls.help, description=cls.help, add_help=False
        )
        localize_help(parser)
        sub = parser.add_subparsers(
            dest="subcommand", required=True, title=t("Subcommands")
        )

        for subcmd in (CleanStateCmd, CleanLogsCmd, CleanCacheCmd, CleanBookCmd):
            subcmd.register(sub)

    @classmethod
    def run(cls, args: Namespace) -> None:
        raise NotImplementedError("CleanCmd should not be executed directly")


class CleanStateCmd(Command):
    name = "state"
    help = t("Clean internal state (runtime state, temp info).")

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument(
            "-y", "--yes", action="store_true", help=t("Skip confirmation prompt")
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        if not STATE_PATH.exists():
            ui.info(t("No internal state found. Nothing to clean."))
            return

        ui.info(t("Internal state file: {path}").format(path=STATE_PATH))

        if not args.yes:
            question = t("Are you sure you want to remove internal state?")
            if not ui.confirm(question, default=False):
                ui.warn(t("Cancelled."))
                return

        try:
            STATE_PATH.unlink()
            ui.success(t("Internal state removed successfully."))
        except Exception as exc:
            fail(t("Failed to remove internal state: {error}").format(error=exc))

        parent = STATE_PATH.parent
        try:
            if parent.exists() and not any(parent.iterdir()):
                parent.rmdir()
        except Exception:
            pass


class CleanLogsCmd(Command):
    name = "logs"
    help = t("Clean log files generated by the application.")

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--config", type=str, help=t("Path to the configuration file")
        )
        parser.add_argument(
            "-y", "--yes", action="store_true", help=t("Skip confirmation prompt")
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help=t("Show what would be removed without deleting anything."),
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            # ``load_or_init_config`` already reported the reason on stderr.
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        log_dir = adapter.get_log_dir()

        if not log_dir.exists():
            ui.info(t("Log directory does not exist: {path}").format(path=log_dir))
            return

        if not log_dir.is_dir():
            fail(t("Log path is not a directory: {path}").format(path=log_dir))

        prefix = f"{PACKAGE_NAME}."
        log_files = [
            f for f in log_dir.iterdir() if f.is_file() and f.name.startswith(prefix)
        ]

        if not log_files:
            ui.info(t("No log files to clean in {path}.").format(path=log_dir))
            return

        ui.info(
            t("Found {count} log files to clean in {path}.").format(
                count=len(log_files), path=log_dir
            )
        )

        if args.dry_run:
            ui.info(t("Dry-run mode: The following files would be removed:"))
            for f in log_files:
                ui.info(f"  - {f.name}")
            return

        if not args.yes:
            question = t("Are you sure you want to remove these log files?")
            if not ui.confirm(question, default=False):
                ui.warn(t("Cancelled."))
                return

        removed_count = 0
        failed_count = 0
        for file in log_files:
            try:
                file.unlink()
                removed_count += 1
                ui.info(t("Removed log file: {file}").format(file=file.name))
            except Exception as exc:
                failed_count += 1
                ui.error(
                    t("Failed to remove log file {file}: {error}").format(
                        file=file.name, error=exc
                    )
                )

        if removed_count > 0:
            ui.success(
                t("Successfully removed {count} log files.").format(count=removed_count)
            )
        else:
            ui.warn(t("No log files were removed."))

        if failed_count > 0:
            raise SystemExit(EXIT_FAILURE)


class CleanCacheCmd(Command):
    name = "cache"
    help = t(
        "Clean cached data for a specific site, or all sites if no site is specified."
    )

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--config", type=str, help=t("Path to the configuration file")
        )
        parser.add_argument(
            "--site",
            help=t("Source site key"),
        )
        parser.add_argument(
            "-y", "--yes", action="store_true", help=t("Skip confirmation prompt")
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help=t("Show what would be removed without deleting anything."),
        )
        parser.add_argument(
            "--json",
            dest="as_json",
            action="store_true",
            help=t("Print a single-line JSON report (requires --dry-run)."),
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        as_json = bool(getattr(args, "as_json", False))
        dry_run = bool(getattr(args, "dry_run", False))
        if as_json and not dry_run:
            fail(t("--json requires --dry-run."), EXIT_USAGE)

        # Validate the site before loading the config: loading may offer to
        # create a default config file, and a bad argument must not cause a
        # side effect (or a prompt) first.
        # ``--site ""`` is an explicit (bad) key, not "no site": treating it
        # as the latter would silently delete every site's cache.
        site = _validated_site(args.site) if args.site is not None else None

        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            # ``load_or_init_config`` already reported the reason on stderr.
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        cache_base = adapter.get_cache_dir()

        if site is not None:
            target_dir = cache_base / site
            target_desc = t("site cache for '{site}'").format(site=site)
        else:
            target_dir = cache_base
            target_desc = t("all site caches")

        if not target_dir.exists():
            if dry_run:
                emit_removal_preview(
                    command="clean cache",
                    items=[],
                    site=site,
                    as_json=as_json,
                )
                return
            ui.info(
                t("No cache found for {desc} at {path}.").format(
                    desc=target_desc, path=target_dir
                )
            )
            return

        if dry_run:
            try:
                # Same root/allow_root arguments as the real removal below.
                item = plan_removal(
                    target_dir, root=cache_base, allow_root=site is None
                )
            except (OSError, ValueError) as exc:
                fail(
                    t("Failed to inspect {desc}: {error}").format(
                        desc=target_desc, error=exc
                    ),
                    EXIT_FAILURE,
                )
            items: list[RemovalItem] = [item] if item is not None else []
            emit_removal_preview(
                command="clean cache",
                items=items,
                site=site,
                as_json=as_json,
            )
            return

        ui.info(t("Cache directory to clean: {path}").format(path=str(target_dir)))

        if not args.yes:
            question = t("Are you sure you want to remove {desc}?").format(
                desc=target_desc
            )
            if not ui.confirm(question, default=False):
                ui.warn(t("Cancelled."))
                return

        try:
            # ``allow_root`` covers the explicit "all site caches" request;
            # a site target must stay strictly inside the cache root.  Links
            # are removed as links, never followed.
            remove_path_safely(target_dir, root=cache_base, allow_root=site is None)
            ui.success(t("Successfully removed {desc}.").format(desc=target_desc))
        except Exception as exc:
            fail(
                t("Failed to remove {desc}: {error}").format(
                    desc=target_desc, error=exc
                )
            )


class CleanBookCmd(Command):
    name = "book"
    help = t("Clean cached raw data for one or more books.")

    @classmethod
    def add_arguments(cls, parser: ArgumentParser) -> None:
        parser.add_argument("book_ids", nargs="*", help=t("Book ID(s)"))
        parser.add_argument(
            "--site",
            help=t("Source site key"),
        )
        parser.add_argument(
            "--config", type=str, help=t("Path to the configuration file")
        )
        parser.add_argument(
            "--start",
            type=str,
            help=t("Start chapter ID (applies only to the first book)"),
        )
        parser.add_argument(
            "--end",
            type=str,
            help=t("End chapter ID (applies only to the first book)"),
        )
        parser.add_argument(
            "--stage",
            type=str,
            default="raw",
            help=t("Cleanup stage (e.g. 'raw', 'cleaner'). Defaults to 'raw'."),
        )

        parser.add_argument(
            "--no-chapters",
            action="store_true",
            help=t("Do not remove chapter data."),
        )
        parser.add_argument(
            "--metadata",
            action="store_true",
            help=t("Remove metadata JSON."),
        )
        parser.add_argument(
            "--media",
            action="store_true",
            help=t("Remove media resources (images, etc)."),
        )
        parser.add_argument(
            "--all",
            action="store_true",
            help=t("Remove all raw data for the book (ignore other flags)."),
        )
        parser.add_argument(
            "-y", "--yes", action="store_true", help=t("Skip confirmation prompt")
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help=t("Show what would be removed without deleting anything."),
        )
        parser.add_argument(
            "--json",
            dest="as_json",
            action="store_true",
            help=t("Print a single-line JSON report (requires --dry-run)."),
        )

    @classmethod
    def run(cls, args: Namespace) -> None:
        as_json = bool(getattr(args, "as_json", False))
        dry_run = bool(getattr(args, "dry_run", False))
        if as_json and not dry_run:
            fail(t("--json requires --dry-run."), EXIT_USAGE)

        if dry_run:
            if args.all and not args.book_ids:
                cls._preview_all(args)
            else:
                cls._preview_book(args)
            return

        if args.all and not args.book_ids:
            cls._remove_all(args)
            return

        cls._remove_book(args)

    @classmethod
    def _preview_all(cls, args: Namespace) -> None:
        # Same ordering and checks as ``_remove_all``: reject an escaping site
        # key before a config load can prompt or create files.
        site = _validated_site(args.site) if args.site is not None else None

        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        raw_data_base = adapter.get_raw_data_dir()

        if site is not None:
            target_dir = raw_data_base / site
            desc = t("all data for site '{site}'").format(site=site)
        else:
            target_dir = raw_data_base
            desc = t("all raw data for all sites")

        as_json = bool(getattr(args, "as_json", False))
        if not target_dir.exists():
            if not as_json:
                ui.info(
                    t("No data found for {desc} at {path}.").format(
                        desc=desc, path=target_dir
                    )
                )
            emit_removal_preview(
                command="clean book",
                items=[],
                site=site,
                as_json=as_json,
            )
            return

        try:
            # Mirror the real removal: the site directory must stay inside the
            # raw-data root; removing the root itself is only allowed when no
            # site was given.
            item = plan_removal(target_dir, root=raw_data_base, allow_root=site is None)
        except (OSError, ValueError) as exc:
            fail(
                t("Failed to inspect {desc}: {error}").format(desc=desc, error=exc),
                EXIT_FAILURE,
            )

        emit_removal_preview(
            command="clean book",
            items=[item] if item is not None else [],
            site=site,
            as_json=as_json,
        )

    @classmethod
    def _preview_book(cls, args: Namespace) -> None:
        books = parse_book_args(args.book_ids, args.start, args.end)

        if not books:
            fail(t("No book IDs provided. Exiting."), EXIT_USAGE)

        for book in books:
            require_safe_book_id(book.book_id)

        stage = args.stage or "raw"
        if not is_safe_path_component(stage):
            fail(
                t("Unsupported stage: {stage!r}").format(stage=stage),
                EXIT_USAGE,
            )

        site: str | None = args.site
        if site is None:
            if not sys.stdin.isatty():
                fail(
                    t(
                        "Interactive selection requires a terminal; "
                        "pass the required arguments explicitly."
                    ),
                    EXIT_USAGE,
                )
            site = ui.prompt(t("Please enter the site key for these book(s):")).strip()
            if not site:
                fail(t("No site provided."), EXIT_USAGE)

        site = _validated_site(site)

        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        raw_site_dir = adapter.get_raw_data_dir() / site

        remove_metadata = args.metadata or False
        remove_chapters = not args.no_chapters
        remove_media = args.media or False
        as_json = bool(getattr(args, "as_json", False))

        if not (remove_chapters or remove_metadata or remove_media):
            # Same no-op as the real cleanup: nothing selected, no prompt.
            if not as_json:
                ui.info(t("Nothing to clean."))
            emit_removal_preview(
                command="clean book",
                items=[],
                site=site,
                book_ids=[book.book_id for book in books],
                as_json=as_json,
            )
            return

        items: list[RemovalItem] = []
        failed = False
        for book in books:
            try:
                items.extend(
                    preview_book_cleanup(
                        raw_site_dir,
                        book,
                        remove_metadata=remove_metadata,
                        remove_chapters=remove_chapters,
                        remove_media=remove_media,
                        remove_all=args.all,
                        stage=stage,
                    )
                )
            except (OSError, ValueError) as exc:
                failed = True
                ui.error(
                    t("Failed to inspect book '{id}': {error}").format(
                        id=book.book_id, error=exc
                    )
                )

        if failed:
            raise SystemExit(EXIT_FAILURE)

        emit_removal_preview(
            command="clean book",
            items=items,
            site=site,
            book_ids=[book.book_id for book in books],
            as_json=as_json,
        )

    @classmethod
    def _remove_all(cls, args: Namespace) -> None:
        # Same ordering as ``clean cache``: reject an escaping site key before
        # a config load can prompt or create files.
        # ``--site ""`` is an explicit (bad) key, not "no site": treating it
        # as the latter would silently delete every site's raw data.
        site = _validated_site(args.site) if args.site is not None else None

        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            # ``load_or_init_config`` already reported the reason on stderr.
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        raw_data_base = adapter.get_raw_data_dir()

        if site is not None:
            target_dir = raw_data_base / site
            desc = t("all data for site '{site}'").format(site=site)
        else:
            target_dir = raw_data_base
            desc = t("all raw data for all sites")

        if not target_dir.exists():
            ui.info(
                t("No data found for {desc} at {path}.").format(
                    desc=desc, path=target_dir
                )
            )
            return

        ui.info(t("Directory to clean: {path}").format(path=str(target_dir)))

        if not args.yes and not ui.confirm(
            t("Are you sure you want to remove {desc}?").format(desc=desc),
            default=False,
        ):
            ui.warn(t("Cancelled."))
            return

        try:
            remove_path_safely(target_dir, root=raw_data_base, allow_root=site is None)
            ui.success(t("Successfully removed {desc}.").format(desc=desc))
        except Exception as exc:
            fail(t("Failed to remove {desc}: {error}").format(desc=desc, error=exc))

    @classmethod
    def _remove_book(cls, args: Namespace) -> None:
        books = parse_book_args(args.book_ids, args.start, args.end)

        if not books:
            fail(t("No book IDs provided. Exiting."), EXIT_USAGE)

        # A book ID becomes one directory name under the raw-data root.  The
        # mixin also checks this, but rejecting the argument before the config
        # is loaded keeps a bad value from prompting/creating files first.
        for book in books:
            require_safe_book_id(book.book_id)

        stage = args.stage or "raw"
        if not is_safe_path_component(stage):
            fail(
                t("Unsupported stage: {stage!r}").format(stage=stage),
                EXIT_USAGE,
            )

        # Determine site; ``--site ""`` is bad input, not a request to prompt.
        site: str | None = args.site
        if site is None:
            if not sys.stdin.isatty():
                fail(
                    t(
                        "Interactive selection requires a terminal; "
                        "pass the required arguments explicitly."
                    ),
                    EXIT_USAGE,
                )
            site = ui.prompt(t("Please enter the site key for these book(s):")).strip()
            if not site:
                fail(t("No site provided."), EXIT_USAGE)

        # Also validated when typed at the prompt: the key reaches the client
        # (and, for ``--all``, the raw-data path), so an escaping value must be
        # refused just like a ``--site`` flag.
        site = _validated_site(site)

        # Load config
        config_path: Path | None = expand_path(args.config) if args.config else None
        config_data = load_or_init_config(config_path)
        if config_data is None:
            # ``load_or_init_config`` already reported the reason on stderr.
            raise SystemExit(EXIT_FAILURE)

        adapter = ConfigAdapter(config=config_data)
        client = registrar.get_client(site, adapter.get_client_config(site))

        remove_all = args.all

        remove_chapters = not args.no_chapters
        remove_metadata = args.metadata or False
        remove_media = args.media or False

        cleanup_failed = False

        if remove_all:
            if not args.yes:
                q = t("Remove ALL raw data for {count} book(s)?").format(
                    count=len(books)
                )
                if not ui.confirm(q, default=False):
                    ui.warn(t("Cancelled."))
                    return

            for book in books:
                ui.info(
                    t("Removing all data for book '{id}'...").format(id=book.book_id)
                )
                try:
                    client.cleanup_book(
                        book,
                        remove_all=True,
                        stage=stage,
                    )
                except Exception as exc:
                    cleanup_failed = True
                    ui.error(
                        t("Failed to clean book '{id}': {error}").format(
                            id=book.book_id, error=exc
                        )
                    )

            if cleanup_failed:
                raise SystemExit(EXIT_FAILURE)
            ui.success(t("Finished cleaning all requested books."))
            return
        summary = []
        if remove_chapters:
            summary.append(t("chapters"))
        if remove_metadata:
            summary.append(t("metadata"))
        if remove_media:
            summary.append(t("media"))

        ui.info(
            t("Preparing to remove: {what}").format(
                what=", ".join(summary) if summary else t("nothing")
            )
        )

        if not summary:
            # ``--no-chapters`` alone (or with only disabled flags) is a no-op;
            # asking to "remove  for N book(s)" would be a malformed prompt.
            ui.info(t("Nothing to clean."))
            return

        if not args.yes:
            q = t("Proceed with removing {what} for {count} book(s)?").format(
                what=", ".join(summary),
                count=len(books),
            )
            if not ui.confirm(q, default=False):
                ui.warn(t("Cancelled."))
                return

        for book in books:
            ui.info(t("Cleaning book '{id}'...").format(id=book.book_id))
            try:
                client.cleanup_book(
                    book,
                    remove_chapters=remove_chapters,
                    remove_metadata=remove_metadata,
                    remove_media=remove_media,
                    stage=stage,
                )
            except Exception as exc:
                cleanup_failed = True
                ui.error(
                    t("Failed to clean book '{id}': {error}").format(
                        id=book.book_id, error=exc
                    )
                )

        if cleanup_failed:
            raise SystemExit(EXIT_FAILURE)
        ui.success(t("Finished cleaning all requested books."))
